#!/usr/bin/env bash

SCRIPT_DIR=$( cd -- "$( dirname -- "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )

# --------------------------------------------------------------
# Oh My Posh
# --------------------------------------------------------------

if [[ "${CHAOTIC_AUR_INSTALLED}" -eq 1 ]]; then
        _installPackages "oh-my-posh-bin"
else
    curl -s https://ohmyposh.dev/install.sh | bash -s -- -d ~/.local/bin
fi

_installAllPackages

# --------------------------------------------------------------
# Prebuilt Packages
# --------------------------------------------------------------

source $SCRIPT_DIR/_prebuilt.sh

# --------------------------------------------------------------
# ML4W Apps
# --------------------------------------------------------------

source $SCRIPT_DIR/_ml4w-apps.sh

# --------------------------------------------------------------
# Flatpaks
# --------------------------------------------------------------

source $SCRIPT_DIR/_flatpaks.sh

# --------------------------------------------------------------
# Cursors
# --------------------------------------------------------------

source $SCRIPT_DIR/_cursors.sh

# --------------------------------------------------------------
# Fonts
# --------------------------------------------------------------

source $SCRIPT_DIR/_fonts.sh

# --------------------------------------------------------------
# Icons
# --------------------------------------------------------------

source $SCRIPT_DIR/_icons.sh

# --------------------------------------------------------------
# Migrate
# --------------------------------------------------------------

source $SCRIPT_DIR/migrate.sh

# --------------------------------------------------------------
# Create XDG Directories
# --------------------------------------------------------------

xdg-user-dirs-update

# --------------------------------------------------------------
# Load custom post installation script
# --------------------------------------------------------------

source $SCRIPT_DIR/custom_setup/setup-arch-post.sh

# --------------------------------------------------------------
# Finish
# --------------------------------------------------------------

_finishMessage
