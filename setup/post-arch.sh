#!/usr/bin/env bash

# --------------------------------------------------------------
# Oh My Posh
# --------------------------------------------------------------

if [[ "${CHAOTIC_AUR_INSTALLED}" -eq 1 ]]; then
        _installPackages "oh-my-posh-bin"
else
    curl -s https://ohmyposh.dev/install.sh | bash -s -- -d ~/.local/bin
fi

_installAllPackages

# --------------------------------------------------------------
# ML4W Settings App
# --------------------------------------------------------------

bash <(curl -s https://raw.githubusercontent.com/mylinuxforwork/ml4w-dotfiles-settings/main/setup.sh)

# --------------------------------------------------------------
# Cursors
# --------------------------------------------------------------

source $repo_path/setup/_cursors.sh

# --------------------------------------------------------------
# Fonts
# --------------------------------------------------------------

source $repo_path/setup/_fonts.sh

# --------------------------------------------------------------
# Icons
# --------------------------------------------------------------

source $repo_path/setup/_icons.sh

# --------------------------------------------------------------
# Create XDG Directories
# --------------------------------------------------------------

xdg-user-dirs-update

# --------------------------------------------------------------
# Load custom post installation script
# --------------------------------------------------------------

source $repo_path/setup/custom_setup/setup-arch-post.sh

# --------------------------------------------------------------
# Migrate
# --------------------------------------------------------------

source $repo_path/setup/migration.sh

# --------------------------------------------------------------
# Finish
# --------------------------------------------------------------

_finishMessage

